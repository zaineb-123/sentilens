function buildFeedbackRows({ startId = 1, count = 110 }) {
  const rows = []; const now = Date.now();
  for (let i = 0; i < count; i += 1) {
    const sentence = SENTENCES[i % SENTENCES.length];
    const department = DEPARTMENTS[i % DEPARTMENTS.length];
    const daysAgo = Math.floor(Math.random() * 90);
    const date = new Date(now - daysAgo * 86400000).toISOString().slice(0, 10);
    rows.push({ id: startId + i, comment: sentence, date, department });
  }
  return rows;
}
function toCsv(rows) {
  const esc = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
  const header = "id,comment,date,department";
  const lines = rows.map((r) => [r.id, esc(r.comment), r.date, r.department].join(","));
  return [header, ...lines].join("\r\n");
}
